/**
 * Returns the supersession-pass-specific surgeon prompt.
 *
 * @returns Supersession pass prompt focused on lineage decisions.
 */
export function getSurgeonSupersessionPassPrompt(): string {
  return [
    "# Supersession Pass",
    "",
    "Your task is to find entries that represent the same fact slot and should be linked via supersession. You are not retiring entries - you are creating lineage.",
    "",
    "## What Supersession Means",
    "",
    "When the world changes, knowledge gets replaced. 'Jim lives in Austin' becomes 'Jim lives in Denver'. The old entry was true at the time but is no longer current. Supersession links the old to the new, preserving the history while marking what is current.",
    "",
    "There are four cases when two entries about the same topic appear:",
    "",
    "1. **Coexisting** - both valid simultaneously ('Jim likes sushi' + 'Jim likes pizza'). No link.",
    "2. **Update** - world changed ('lives in Austin' -> 'lives in Denver'). Old was true, now is not.",
    "3. **Correction** - old was wrong ('moved in March' -> 'actually moved in February'). Old was never true.",
    "4. **Refinement** - new is more specific ('lives in Denver' -> 'lives in Denver's Baker neighborhood').",
    "5. **Duplicate** - same fact, different wording. Link the weaker version as a duplicate.",
    "",
    "**Coexistence is the most common case.** Most entries with the same subject are additive, not replacements. Do not over-link.",
    "",
    "## Working Method",
    "",
    "1. **Orient** - Call `get_health_stats` to understand the corpus.",
    "",
    "2. **Query clusters** - Call `query_supersession_candidates` starting with `scope = 'claim_key'` (highest confidence). Each result is a cluster of active entries that share a claim key or subject.",
    "",
    "3. **Evaluate each cluster** - Read the entries in the cluster. For each pair, decide: coexistence, update, correction, refinement, or duplicate?",
    "",
    "4. **Act on clear cases** - Use `link_supersession` when the relationship is clear. Use `assign_claim_key` to normalize inconsistent keys. Use `set_validity` when temporal bounds are obvious from the content.",
    "",
    "5. **Skip ambiguous cases** - When you are not confident, skip. Record the skip in `complete_pass`.",
    "",
    "6. **Widen scope** - After exhausting claim_key clusters, widen to `scope = 'subject'` if budget allows.",
    "",
    "7. **Complete** - Call `complete_pass` when clusters are exhausted or budget is tight.",
    "",
    "## Hard Rules",
    "",
    "- No cross-type supersession",
    "- No milestone supersession",
    "- No core-expiry supersession",
    "- No self-links",
    "",
    "## Coexistence Examples (Do Not Link These)",
    "",
    "- 'Jim prefers dark mode' + 'Jim prefers vim keybindings' - different preferences, both valid",
    "- 'The API rate limit is 100/min' + 'The API has a 10MB upload limit' - different attributes of the same system",
    "- 'Use pnpm for the monorepo' + 'Use npm for standalone scripts' - different contexts, both valid",
    "- 'agenr uses SQLite' + 'agenr stores entries with embeddings' - different aspects of the same project",
    "",
    "## Supersession Examples (Do Link These)",
    "",
    "- 'Jim lives in Austin' + 'Jim lives in Denver' - same slot, world changed -> kind=update",
    "- 'The API endpoint is /v1/users' + 'The API endpoint is /v2/users' - same slot, version changed -> kind=update",
    "- 'Meeting is on Thursday' + 'Meeting was rescheduled to Friday' - same slot, correction -> kind=correction",
    "- 'Mac mini hostname is mini' + 'Mac mini hostname is mini.local (full hostname is mini)' - same slot, more detail -> kind=refinement",
    "",
    "## Duplicate Handling",
    "",
    "When two entries say the same thing in different words:",
    "1. Pick the better-written, more complete, or higher-importance one as the survivor.",
    "2. Link the weaker one with `kind = 'duplicate'`.",
    "3. The weaker one gets superseded, not retired - lineage is preserved.",
    "",
    "## Claim Key Normalization",
    "",
    "When you find entries that describe the same slot but have different claim keys (for example, `mac_mini/manual_update_policy` vs `mac_mini_update_control/manual_approval_required`), use `assign_claim_key` to normalize the inconsistent one to match the better key before linking.",
    "",
    "## Budget Awareness",
    "",
    "- Process claim_key clusters first - they are the highest-confidence candidates.",
    "- Subject clusters require more judgment - save budget for them.",
    "- Do not inspect entries unnecessarily - the cluster query already includes content.",
    "- If budget is tight, complete after the claim_key sweep rather than rushing through the subject sweep.",
  ].join("\n");
}
