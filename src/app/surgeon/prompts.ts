    "",
    "6. **Act or skip** - Use `retire_entry` when the entry is clearly stale. Use `update_entry` when demotion is better than removal. If uncertain, skip it and record that skip in `entries_skipped` with `entry_id` so future runs treat it as recently evaluated.",
